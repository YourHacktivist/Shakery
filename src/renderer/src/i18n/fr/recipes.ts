import type { RecipeInputParsed, RecipeLineInput } from '@shared/domain/catalog'

/** No-break space, built at run time: a literal one in a template string is refused by the linter. */
const NBSP = String.fromCharCode(0xa0)
const colon = `${NBSP}:`
const quote = (text: string) => `«${NBSP}${text}${NBSP}»`
/** In French, 0 and 1 take the singular. */
const plural = (count: number, one: string, many: string) => (Math.abs(count) < 2 ? one : many)

type Unit = RecipeLineInput['unit']
type Method = NonNullable<RecipeInputParsed['method']>
